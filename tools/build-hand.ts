// Precomputes the anatomical hand (mesh, skin weights, nails and strokes) into a compact data
// module, so phones never run the 2-second surface extraction. Run: npm run build:hand
import { writeFileSync } from 'node:fs';
import { deflateSync } from 'fflate';
import { buildHandSurface, buildNails, skinWeights } from '../src/hands3d/geometry';
import { buildStrokes, strokeRibbons } from '../src/hands3d/strokes';

const t0 = Date.now();
const mesh = buildHandSurface(2.3);
const n = mesh.positions.length / 3;
const skinIdx = new Uint8Array(n * 4), skinW = new Uint8Array(n * 4);
for (let v = 0; v < n; v++) {
  const [si, sw] = skinWeights([mesh.positions[v * 3], mesh.positions[v * 3 + 1], mesh.positions[v * 3 + 2]], mesh.parts[v]);
  let acc = 0;
  for (let k = 0; k < 4; k++) {
    skinIdx[v * 4 + k] = si[k];
    const q = k === 3 ? 255 - acc : Math.round(sw[k] * 255);
    skinW[v * 4 + k] = Math.max(0, q); acc += Math.max(0, q);
  }
}
// nails as a small skinned mesh of their own
const nails = buildNails();
const nP: number[] = [], nN: number[] = [], nI: number[] = [], nSI: number[] = [], nSW: number[] = [];
for (const nail of nails) {
  const base = nP.length / 3, R = nail.grid.length, C = nail.grid[0].length;
  nail.grid.forEach((row, i) => row.forEach((p, k) => {
    nP.push(...p); nN.push(...nail.normal[i][k]);
    const [si, sw] = skinWeights(p, nail.finger); nSI.push(...si); nSW.push(...sw);
  }));
  for (let i = 0; i < R - 1; i++) for (let k = 0; k < C - 1; k++) { const a = base + i * C + k; nI.push(a, a + 1, a + C, a + 1, a + C + 1, a + C); }
}
const st = strokeRibbons(buildStrokes());

const q16 = (a: ArrayLike<number>, s: number) => Int16Array.from(a, (x) => Math.round(x * s));
const q8 = (a: ArrayLike<number>) => Int8Array.from(a, (x) => Math.round(Math.max(-1, Math.min(1, x)) * 127));
const blobs: Record<string, ArrayBufferView> = {
  pos: q16(mesh.positions, 100), nor: q8(mesh.normals), idx: Uint16Array.from(mesh.indices), part: mesh.parts, si: skinIdx, sw: skinW,
  nailPos: q16(nP, 100), nailNor: q8(nN), nailIdx: Uint16Array.from(nI), nailSi: Uint8Array.from(nSI), nailSw: Uint8Array.from(nSW, (x) => Math.round(x * 255)),
  stPos: q16(st.positions, 100), stNor: q8(st.normals), stSide: q8(st.sides), stOff: q8(st.offs.map((x) => x / 1.2)), stAlpha: Uint8Array.from(st.alpha, (x) => Math.round(x * 255)),
  stSi: Uint8Array.from(st.skinIdx), stSw: Uint8Array.from(st.skinW, (x) => Math.round(x * 255)), stIdx: Uint16Array.from(st.indices),
};
const layout: Record<string, [number, number, string]> = {};
let off = 0;
const parts: Uint8Array[] = [];
for (const [k, v] of Object.entries(blobs)) {
  const u8 = new Uint8Array(v.buffer, v.byteOffset, v.byteLength);
  const pad = (8 - (off % 8)) % 8;
  if (pad) { parts.push(new Uint8Array(pad)); off += pad; }
  layout[k] = [off, v.byteLength, v.constructor.name];
  parts.push(u8); off += u8.length;
}
const all = new Uint8Array(off);
let o = 0; for (const p of parts) { all.set(p, o); o += p.length; }
const z = deflateSync(all, { level: 9 });
const b64 = Buffer.from(z).toString('base64');
writeFileSync('src/hands3d/handData.ts',
  `// GENERATED by tools/build-hand.ts — do not edit. Anatomical hand: ${n} vertices, ${mesh.indices.length / 3} triangles,\n` +
  `// ${nails.length} nails, ${st.indices.length / 3} stroke triangles. Units: 0.01 mm (positions).\n` +
  `export const HAND_LAYOUT: Record<string, [number, number, string]> = ${JSON.stringify(layout)};\n` +
  `export const HAND_DATA = '${b64}';\n`);
console.log(`hand: ${n} verts, ${mesh.indices.length / 3} tris, strokes ${st.positions.length / 3} verts; ${all.length} bytes -> ${z.length} deflated; ${Date.now() - t0} ms`);
