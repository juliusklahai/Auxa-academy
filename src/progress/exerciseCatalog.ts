// The exercise catalog the server uses to witness attempts (see migration 0008): every exercise with its
// level, how many passes it needs, the pass mark, how many note groups it has, and the least real time a
// genuine attempt can take. Generated into SQL by scripts/exerciseCatalog.ts; a test keeps it in sync.
import { LESSONS } from '../curriculum/lessons';
import type { Exercise } from '../core/types';

export interface CatalogRow { id: string; lesson: string; level: number; track: string; piece: boolean; passes: number; passScore: number; groups: number; minMs: number }

export function minMs(e: Exercise): number {
  if (e.drill) return (e.drill.rounds ?? 10) * 1200;
  const groups = e.events.filter((x) => x.pitches.length).length;
  if (e.mode === 'wait') return Math.max(1500, groups * 150);
  const beats = Math.max(0, ...e.events.map((x) => x.beat + x.beats));
  return Math.max(1500, Math.round(((beats * 60000) / (e.tempo || 90)) * 0.6)); // allows playing up to ~1.6x faster
}
export const groupsOf = (e: Exercise) => (e.drill ? e.drill.rounds ?? 10 : e.events.filter((x) => x.pitches.length).length);

export function exerciseCatalog(): CatalogRow[] {
  const seen = new Set<string>();
  const rows: CatalogRow[] = [];
  for (const l of LESSONS) for (const e of l.exercises) {
    if (seen.has(e.id)) continue;
    seen.add(e.id);
    rows.push({ id: e.id, lesson: l.id, level: l.level, track: l.track ?? 'piano', piece: !!e.backing, passes: e.requiredPasses, passScore: e.passScore ?? 80, groups: groupsOf(e), minMs: minMs(e) });
  }
  return rows;
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
export function catalogSql(): string {
  const rows = exerciseCatalog();
  return `-- GENERATED by scripts/exerciseCatalog.ts from the curriculum. Do not edit by hand; run it again when lessons change,
-- then run this file in the Supabase SQL editor.
begin;
delete from private.exercise_catalog;
insert into private.exercise_catalog (id, lesson_id, level, track, piece, required_passes, pass_score, groups, min_ms) values
${rows.map((r) => `  (${q(r.id)}, ${q(r.lesson)}, ${r.level}, ${q(r.track)}, ${r.piece}, ${r.passes}, ${r.passScore}, ${r.groups}, ${r.minMs})`).join(',\n')};
commit;
`;
}
